// Style is a style of ox program.
type Style string

// Styles.
const (
	// StyleHand builds the program by hand, with ox.Run and ox.Flags().
	StyleHand Style = "hand"
	// StyleReflect builds the flags of each command from a struct with ox
	// tags, with ox.From.
	StyleReflect Style = "reflect"
	// StyleApp builds the program from a struct and its doc comments, with
	// ox.AppFrom. `go generate` writes the doc comments with oxdoc.
	StyleApp Style = "app"
)

// Styles are the styles, in the order that the importer writes them.
var Styles = []Style{StyleHand, StyleReflect, StyleApp}

// Write writes the program of root in a style, and formats it.
func Write(root *Command, style Style) ([]byte, error) {
	w := &writer{root: written(root, nil)}
	switch style {
	case StyleHand:
		w.hand()
	case StyleReflect:
		w.reflect()
	case StyleApp:
		w.app()
	default:
		return nil, fmt.Errorf("unknown style %q", style)
	}
	src, err := format.Source(w.buf.Bytes())
	if err != nil {
		return nil, fmt.Errorf("formatting %s style of %s: %w\n%s", style, root.Name, err, w.buf.Bytes())
	}
	return src, nil
}

// writer writes a program.
type writer struct {
	// root is the root command.
	root *Command
	// buf holds the source.
	buf bytes.Buffer
}

// printf writes to the source.
func (w *writer) printf(format string, v ...any) {
	_, _ = fmt.Fprintf(&w.buf, format, v...)
}

// header writes the comments and the package clause.
func (w *writer) header(style Style) {
	w.printf("// Code generated by oximport. DO NOT EDIT.\n\n")
	name := w.root.Name
	w.printf("// Command %s is an ox version of %s, in the %s style. oximport wrote it\n", name, name, style)
	w.printf("// from the help of %s.\n", name)
	if style == StyleApp {
		w.printf("//\n// Run go generate before go build. It writes the doc comments in\n// oxdoc_gen.go, which ox.AppFrom reads.\n")
	}
	w.printf("package main\n\n")
	if style == StyleApp {
		w.printf("//go:generate go run github.com/xo/ox/cmd/oxdoc\n\n")
	}
}

// imports writes the import block.
func (w *writer) imports() {
	w.printf("import (\n\t\"github.com/xo/ox\"\n")
	if w.getopt() {
		w.printf("\t\"github.com/xo/ox/text\"\n")
	}
	w.printf(")\n\n")
	if w.getopt() {
		w.printf("func init() {\n\ttext.FlagSpecSpacer = \"=\"\n}\n\n")
	}
}

// getopt returns true when the program writes `--name=VALUE` in its help.
func (w *writer) getopt() bool {
	return w.root.Format == FormatGNU || w.root.Format == FormatPsql
}

// hand writes the hand-built style.
func (w *writer) hand() {
	w.header(StyleHand)
	w.imports()
	w.printf("func main() {\n\tox.Run(\n")
	w.command(w.root, 2, func(cmd *Command, indent string) {
		flags := cmd.Flags
		if len(flags) == 0 {
			return
		}
		w.printf("%sox.Flags().\n", indent)
		for i, g := range flags {
			sep := "."
			if i == len(flags)-1 {
				sep = ","
			}
			w.printf("%s\t%s%s", indent, handFlag(g), sep)
			if c := comment(g); c != "" {
				w.printf(" // %s", c)
			}
			w.printf("\n")
		}
	})
	w.printf("\t)\n}\n")
}

// reflect writes the reflection style.
func (w *writer) reflect() {
	w.header(StyleReflect)
	w.imports()
	w.root.Walk(func(cmd *Command) {
		flags := cmd.Flags
		if len(flags) == 0 {
			return
		}
		name := typeName(cmd, "Args")
		w.printf("// %s are the flags of %s.\n", name, strings.Join(cmd.Tree(), " "))
		w.printf("type %s struct {\n", name)
		for _, f := range fields(flags) {
			w.printf("\t%s %s %s", f.name, f.typ, structTag(append([]string{f.flag.Usage}, f.opts...)))
			if c := comment(f.flag); c != "" {
				w.printf(" // %s", c)
			}
			w.printf("\n")
		}
		w.printf("}\n\n")
	})
	w.printf("func main() {\n\tox.Run(\n")
	w.command(w.root, 2, func(cmd *Command, indent string) {
		if len(cmd.Flags) != 0 {
			w.printf("%sox.From(new(%s)),\n", indent, typeName(cmd, "Args"))
		}
	})
	w.printf("\t)\n}\n")
}

// command writes the options of a command. flags writes the options of its
// flags.
func (w *writer) command(cmd *Command, depth int, flags func(*Command, string)) {
	indent := strings.Repeat("\t", depth)
	opt := func(format string, v ...any) {
		w.printf("%s"+format+",\n", append([]any{indent}, v...)...)
	}
	if cmd.Parent == nil {
		if len(cmd.Sections) != 0 {
			opt("ox.Defaults(ox.Sections(%s))", quoteList(cmd.Sections))
		} else {
			opt("ox.Defaults()")
		}
	} else if len(cmd.Sections) != 0 {
		opt("ox.Help(ox.Sections(%s))", quoteList(cmd.Sections))
	}
	usage := cmd.Usage
	if cmd.Parent == nil {
		usage = ""
	}
	opt("ox.Usage(%s, %s)", lit(cmd.Name), lit(usage))
	if cmd.Banner != "" {
		opt("ox.Banner(%s)", lit(cmd.Banner))
	}
	if cmd.Spec != "" {
		opt("ox.Spec(%s)", lit(cmd.Spec))
	}
	if len(cmd.Aliases) != 0 {
		opt("ox.Aliases(%s)", quoteList(cmd.Aliases))
	}
	if cmd.Example != "" {
		opt("ox.Example(%s)", lit("\n"+cmd.Example))
	}
	if cmd.Section >= 0 && cmd.Parent != nil {
		opt("ox.Section(%d)", cmd.Section)
	}
	if len(cmd.CommandSections) != 0 {
		opt("ox.Sections(%s)", quoteList(cmd.CommandSections))
	}
	if footer := cmd.Footer; footer != "" && footer != defaultFooter(cmd) {
		opt("ox.Footer(%s)", lit(footer))
	}
	flags(cmd, indent)
	for _, c := range cmd.Commands {
		w.printf("%sox.Sub( // %s\n", indent, strings.Join(c.Tree(), " "))
		w.command(c, depth+1, flags)
		w.printf("%s),\n", indent)
	}
}

// defaultFooter returns the footer that ox writes for the command.
func defaultFooter(cmd *Command) string {
	if len(cmd.Commands) == 0 {
		return ""
	}
	return fmt.Sprintf(text.Footer, strings.Join(cmd.Tree(), " "))
}

// written returns a copy of the tree of cmd with only the flags that the
// program defines on each command, and only the sections that they use. It
// leaves out a flag that a parent defines. It keeps a help or version flag
// only on the root, and only when it differs from the flag that ox adds.
func written(cmd, parent *Command) *Command {
	c := *cmd
	c.Parent, c.Flags, c.Commands = parent, nil, nil
	c.Sections = slices.Clone(cmd.Sections)
	for _, g := range cmd.Flags {
		switch {
		case cmd.Inherits(g.Name):
		case g.Hook != "" && cmd.Parent != nil:
		case g.Hook == "help" && g.Short == text.HelpFlagShort && g.Section == -1:
		case g.Hook == "version" && g.Short == text.VersionFlagShort && g.Section == -1:
		default:
			f := *g
			c.Flags = append(c.Flags, &f)
		}
	}
	for _, sub := range cmd.Commands {
		c.Commands = append(c.Commands, written(sub, &c))
	}
	compactSections(&c)
	return &c
}

// handFlag returns the call that defines a flag, such as
// String("file", "execute commands from file", ox.Short("f")).
func handFlag(g *Flag) string {
	method, ok := flagMethods[g.Type]
	typ := ""
	if !ok {
		method, typ = "Var", ", ox."+typeConst(g.Type)
	}
	var opts []string
	if g.Hook != "" {
		opts = append(opts, fmt.Sprintf("ox.Special(%q)", "hook:"+g.Hook))
	}
	if g.Elem != "" && g.Elem != ox.StringT {
		opts = append(opts, "ox.Elem(ox."+typeConst(g.Elem)+")")
	}
	if g.Spec != "" && g.Hook == "" {
		opts = append(opts, fmt.Sprintf("ox.Spec(%s)", lit(g.Spec)))
	}
	switch {
	case g.Hook != "":
	case g.Optional:
		opts = append(opts, fmt.Sprintf("ox.NoArg(true, %s)", lit(g.Default)))
	case g.Default != "":
		opts = append(opts, fmt.Sprintf("ox.Default(%s)", lit(g.Default)))
	}
	if g.Short != "" {
		opts = append(opts, fmt.Sprintf("ox.Short(%s)", lit(g.Short)))
	}
	if len(g.Aliases) != 0 {
		opts = append(opts, fmt.Sprintf("ox.Aliases(%s)", quoteList(g.Aliases)))
	}
	if g.Exact && len(g.Values) != 0 && g.Hook == "" {
		opts = append(opts, fmt.Sprintf("ox.Valid(%s)", quoteList(g.Values)))
	}
	if g.Section >= 0 {
		opts = append(opts, fmt.Sprintf("ox.Section(%d)", g.Section))
	}
	s := fmt.Sprintf("%s(%s, %s%s", method, lit(g.Name), lit(g.Usage), typ)
	if len(opts) != 0 {
		s += ", " + strings.Join(opts, ", ")
	}
	return s + ")"
}

// flagMethods are the methods of [ox.FlagSet] for each type.
var flagMethods = map[ox.Type]string{
	ox.StringT:   "String",
	ox.BoolT:     "Bool",
	ox.IntT:      "Int",
	ox.Int64T:    "Int64",
	ox.Int32T:    "Int32",
	ox.Int16T:    "Int16",
	ox.Int8T:     "Int8",
	ox.UintT:     "Uint",
	ox.Uint64T:   "Uint64",
	ox.Uint32T:   "Uint32",
	ox.Uint16T:   "Uint16",
	ox.Uint8T:    "Uint8",
	ox.Float64T:  "Float64",
	ox.Float32T:  "Float32",
	ox.DurationT: "Duration",
	ox.CountT:    "Count",
	ox.PathT:     "Path",
	ox.AddrT:     "Addr",
	ox.CIDRT:     "CIDR",
	ox.HexT:      "Hex",
	ox.Base64T:   "Base64",
	ox.SliceT:    "Slice",
	ox.ArrayT:    "Array",
	ox.MapT:      "Map",
}

// typeConst returns the name of the constant of a type, such as IntT.
func typeConst(typ ox.Type) string {
	switch typ {
	case ox.UUIDT, ox.URLT, ox.CIDRT:
		return strings.ToUpper(string(typ)) + "T"
	case ox.AddrPortT:
		return "AddrPortT"
	case ox.DateTimeT:
		return "DateTimeT"
	case ox.BigIntT:
		return "BigIntT"
	case ox.BigFloatT:
		return "BigFloatT"
	case ox.BigRatT:
		return "BigRatT"
	}
	s := string(typ)
	return strings.ToUpper(s[:1]) + s[1:] + "T"
}

// comment returns what the program cannot say about a flag, for a comment.
func comment(g *Flag) string {
	var v []string
	if g.Note != "" {
		v = append(v, "psql writes -"+g.Short+" "+g.Note)
	}
	if g.Required {
		v = append(v, "required")
	}
	switch {
	case g.Hook != "" && len(g.Values) != 0:
		v = append(v, "values: "+strings.Join(g.Values, ", "))
	case !g.Exact && len(g.Values) > maxValues:
		v = append(v, "completes: "+strings.Join(g.Values[:maxValues], ", ")+", ...")
	case !g.Exact && len(g.Values) != 0:
		v = append(v, "completes: "+strings.Join(g.Values, ", "))
	}
	switch {
	case g.Path == "dir":
		v = append(v, "completes a directory")
	case g.Path == "file" && len(g.Exts) != 0:
		v = append(v, "completes a file: "+strings.Join(g.Exts, ", "))
	case g.Path == "file":
		v = append(v, "completes a file")
	}
	return strings.Join(v, "; ")
}

// maxValues is the number of values that a comment lists.
const maxValues = 8

// field is a field of a struct for the reflection and app styles.
type field struct {
	// name is the name of the field.
	name string
	// typ is the Go type of the field.
	typ string
	// opts are the options of the ox tag, after the description.
	opts []string
	// flag is the flag.
	flag *Flag
}

// fields returns the fields of a struct for flags.
func fields(flags []*Flag) []field {
	var v []field
	seen := make(map[string]bool)
	for _, g := range flags {
		name := goName(g.Name)
		for i := 2; seen[name]; i++ {
			name = goName(g.Name) + strconv.Itoa(i)
		}
		seen[name] = true
		typ, opts := fieldType(g)
		if mapped := ox.DefaultFlagNameMapper(name); mapped != g.Name {
			opts = append([]string{"name:" + g.Name}, opts...)
		}
		if g.Hook != "" {
			opts = append(opts, "hook:"+g.Hook)
		}
		if g.Spec != "" && g.Hook == "" {
			opts = append(opts, "spec:"+g.Spec)
		}
		switch {
		case g.Hook != "":
		case g.Optional:
			opts = append(opts, "noarg:"+g.Default)
		case g.Default != "":
			opts = append(opts, "default:"+g.Default)
		}
		if g.Short != "" {
			opts = append(opts, "short:"+g.Short)
		}
		switch len(g.Aliases) {
		case 0:
		case 1:
			opts = append(opts, "alias:"+g.Aliases[0])
		default:
			opts = append(opts, "aliases:"+strings.Join(g.Aliases, "|"))
		}
		if g.Section >= 0 {
			opts = append(opts, "section:"+strconv.Itoa(g.Section))
		}
		v = append(v, field{name: name, typ: typ, opts: opts, flag: g})
	}
	return v
}

// fieldType returns the Go type of the field of a flag, and the tag options
// that set its type. A type that has no Go type that ox knows is a string
// with the type option.
func fieldType(g *Flag) (string, []string) {
	switch g.Type {
	case ox.BoolT, ox.StringT, ox.IntT, ox.Int64T, ox.UintT, ox.Uint64T, ox.Float64T, ox.Float32T:
		return string(g.Type), nil
	case ox.CountT:
		return "int", []string{"type:count"}
	case ox.SliceT, ox.ArrayT:
		var opts []string
		if g.Type == ox.ArrayT {
			opts = append(opts, "type:array")
		}
		switch g.Elem {
		case "", ox.StringT:
			return "[]string", opts
		case ox.IntT, ox.Int64T, ox.UintT, ox.Float64T, ox.BoolT:
			return "[]" + string(g.Elem), opts
		}
		return "[]string", append(opts, "elem:"+string(g.Elem))
	case ox.MapT:
		if g.Elem == "" || g.Elem == ox.StringT {
			return "map[string]string", nil
		}
		return "map[string]string", []string{"elem:" + string(g.Elem)}
	}
	return "string", []string{"type:" + string(g.Type)}
}

// structTag returns the ox tag of a field, as a Go string. Each part is
// escaped for ox, which splits the tag at each comma that has no backslash
// before it. See "Escaping in a struct tag" in docs/DESIGN.md.
func structTag(parts []string) string {
	v := make([]string, len(parts))
	for i, s := range parts {
		v[i] = strings.NewReplacer(`\`, `\\`, `,`, `\,`).Replace(s)
	}
	tag := "ox:" + strconv.Quote(strings.Join(v, ","))
	if strings.Contains(tag, "`") {
		return strconv.Quote(tag)
	}
	return "`" + tag + "`"
}

// typeName returns the name of the struct type of a command, such as
// PrListArgs.
func typeName(cmd *Command, suffix string) string {
	path := cmd.Path()
	if len(path) == 0 {
		if suffix == "Command" {
			return "App"
		}
		return suffix
	}
	var sb strings.Builder
	for _, s := range path {
		_, _ = sb.WriteString(goName(s))
	}
	return sb.String() + suffix
}

// goName returns an exported Go identifier for a name, such as
// SingleTransaction for single-transaction.
func goName(name string) string {
	var sb strings.Builder
	upper := true
	for _, c := range name {
		switch {
		case !unicode.IsLetter(c) && !unicode.IsDigit(c):
			upper = true
		case upper:
			_, _ = sb.WriteRune(unicode.ToUpper(c))
			upper = false
		default:
			_, _ = sb.WriteRune(c)
		}
	}
	s := sb.String()
	if s == "" || !unicode.IsLetter([]rune(s)[0]) {
		s = "Flag" + s
	}
	return s
}

// lit returns s as a Go string literal. A string of more than one line is a
// raw string, when it can be one.
func lit(s string) string {
	if strings.Contains(s, "\n") && !strings.ContainsAny(s, "`\r") && strconv.CanBackquote(strings.ReplaceAll(s, "\n", "")) {
		return "`" + s + "`"
	}
	return strconv.Quote(s)
}

// quoteList returns each string as a Go string literal, separated by commas.
func quoteList(v []string) string {
	s := make([]string, len(v))
	for i, t := range v {
		s[i] = strconv.Quote(t)
	}
	return strings.Join(s, ", ")
}
