// Command oxdoc writes the doc comments of the struct types of a Go package
// into a file of that package, so that [ox.App] and [ox.From] can read them
// when the program runs. Go keeps no doc comment in a program.
//
// Add this line to a file of the package, and run `go generate`:
//
//	//go:generate go run github.com/xo/ox/cmd/oxdoc
//
// oxdoc reads each Go file in the directory, other than the test files and
// the file that it writes. It writes a call to [ox.RegisterDoc] for each
// struct type that has a doc comment, or a field with a doc comment.
package main

import (
	"bytes"
	"context"
	"errors"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"maps"
	"os"
	"path/filepath"
	"slices"
	"strconv"
	"strings"

	"github.com/xo/ox"
)

func main() {
	args := struct {
		Out string `ox:"the file to write,short:o,default:oxdoc_gen.go"`
	}{}
	ox.Run(
		ox.Usage("oxdoc", "write the doc comments of struct types for ox"),
		ox.Spec("[flags] [dir]"),
		ox.Defaults(),
		ox.From(&args),
		ox.ValidArgs(0, 1),
		ox.Exec(func(_ context.Context, v []string) error {
			dir := "."
			if len(v) != 0 {
				dir = v[0]
			}
			return run(dir, args.Out)
		}),
	)
}

// run reads the package in dir and writes the file out in dir.
func run(dir, out string) error {
	if !filepath.IsAbs(out) {
		out = filepath.Join(dir, out)
	}
	files, err := filepath.Glob(filepath.Join(dir, "*.go"))
	if err != nil {
		return err
	}
	srcs := make(map[string][]byte)
	for _, name := range files {
		if strings.HasSuffix(name, "_test.go") || filepath.Clean(name) == filepath.Clean(out) {
			continue
		}
		if srcs[name], err = os.ReadFile(name); err != nil {
			return err
		}
	}
	buf, err := Generate(srcs)
	if err != nil {
		return err
	}
	return os.WriteFile(out, buf, 0o644)
}

// Generate returns the source of a file that registers the doc comments of
// the struct types in the sources, by file name. Each source is a file of
// one package. A file with a build constraint is read like any other.
func Generate(srcs map[string][]byte) ([]byte, error) {
	fset := token.NewFileSet()
	var pkg string
	var types []typeDoc
	for _, name := range slices.Sorted(maps.Keys(srcs)) {
		f, err := parser.ParseFile(fset, name, srcs[name], parser.ParseComments)
		if err != nil {
			return nil, err
		}
		switch {
		case pkg == "":
			pkg = f.Name.Name
		case pkg != f.Name.Name:
			return nil, fmt.Errorf("%s: package %s is not package %s", name, f.Name.Name, pkg)
		}
		types = append(types, structDocs(f)...)
	}
	if pkg == "" {
		return nil, errors.New("no Go file")
	}
	var buf bytes.Buffer
	fmt.Fprintf(&buf, "// Code generated by oxdoc. DO NOT EDIT.\n\npackage %s\n\n", pkg)
	if len(types) != 0 {
		fmt.Fprintf(&buf, "import \"github.com/xo/ox\"\n\nfunc init() {\n")
		for _, typ := range types {
			fmt.Fprintf(&buf, "\tox.RegisterDoc[%s](%s, ", typ.name, strconv.Quote(typ.doc))
			if len(typ.fields) == 0 {
				fmt.Fprintf(&buf, "nil)\n")
				continue
			}
			fmt.Fprintf(&buf, "map[string]string{\n")
			for _, field := range typ.fields {
				fmt.Fprintf(&buf, "\t\t%s: %s,\n", strconv.Quote(field.name), strconv.Quote(field.doc))
			}
			fmt.Fprintf(&buf, "\t})\n")
		}
		fmt.Fprintf(&buf, "}\n")
	}
	return format.Source(buf.Bytes())
}

// typeDoc is the doc comment of a struct type and of its fields.
type typeDoc struct {
	name   string
	doc    string
	fields []fieldDoc
}

// fieldDoc is the doc comment of a field.
type fieldDoc struct {
	name string
	doc  string
}

// structDocs returns the doc comment of each struct type in f that has one,
// or that has a field with one. It skips a generic type, because a call to
// [ox.RegisterDoc] needs the type arguments.
func structDocs(f *ast.File) []typeDoc {
	var types []typeDoc
	for _, decl := range f.Decls {
		gd, ok := decl.(*ast.GenDecl)
		if !ok || gd.Tok != token.TYPE {
			continue
		}
		for _, spec := range gd.Specs {
			ts := spec.(*ast.TypeSpec)
			st, ok := ts.Type.(*ast.StructType)
			if !ok || ts.TypeParams != nil {
				continue
			}
			doc := ts.Doc
			if doc == nil && len(gd.Specs) == 1 {
				doc = gd.Doc
			}
			typ := typeDoc{name: ts.Name.Name, doc: doc.Text()}
			for _, field := range st.Fields.List {
				s := field.Doc.Text()
				if s == "" {
					continue
				}
				for _, name := range field.Names {
					typ.fields = append(typ.fields, fieldDoc{name: name.Name, doc: s})
				}
			}
			if typ.doc != "" || len(typ.fields) != 0 {
				types = append(types, typ)
			}
		}
	}
	return types
}
